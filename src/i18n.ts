export function fmtDate(ts: number | Date = new Date()): string {
  const d = new Date(ts);
  const p = (n: number) => String(n).padStart(2, "0");
  return `${p(d.getDate())}.${p(d.getMonth() + 1)}.${d.getFullYear()}`;
}

/** Decimal comma, as used in all three languages. */
export const fmtNum = (v: number, digits?: number) =>
  (digits === undefined ? String(v) : v.toFixed(digits)).replace(".", ",");
